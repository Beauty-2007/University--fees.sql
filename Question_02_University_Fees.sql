-- ICT371 Question 2: University Fee Payments
-- PostgreSQL / PLpgSQL. Run in a fresh database.
CREATE TABLE students (
 student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_number VARCHAR(30) NOT NULL UNIQUE, full_name VARCHAR(120) NOT NULL,
 fee_due NUMERIC(12,2) NOT NULL CHECK(fee_due>=0)
);
CREATE TABLE payments (
 payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id INT NOT NULL REFERENCES students(student_id),
 amount NUMERIC(12,2) NOT NULL CHECK(amount>0), paid_on DATE NOT NULL
);
CREATE TABLE payment_audit (
 audit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id INT NOT NULL REFERENCES payments(payment_id),
 student_id INT NOT NULL REFERENCES students(student_id),
 amount NUMERIC(12,2) NOT NULL, logged_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE daily_collections (
 collection_date DATE PRIMARY KEY,payment_count BIGINT NOT NULL,total_amount NUMERIC(12,2) NOT NULL
);
